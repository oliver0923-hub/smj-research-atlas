"""Public, narrowly bounded SMJ single-DOI Open Access analysis API.

All requests use canonical Atlas DOI identity; the caller may not supply a URL
or article body. Full text is transient, legally sourced and never stored or
re-published. Unlike GitHub Pages alone, a server can retrieve OA documents
without assuming publisher CORS headers.
"""
import hashlib
import json
import os
import re
import threading
import time
from collections import defaultdict, deque
from datetime import datetime, timezone
from urllib.parse import quote

import httpx
from fastapi import FastAPI, HTTPException, Request
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, Field

from .article import digest, parse_article
from .network import OAFetcher, PolicyError
from .on_demand import article_type, field_status, concise_rows
from .research import extraction, validate_record
from .selection import source_candidates
from .wiley import merge_wiley_candidate

BASE="https://oliver0923-hub.github.io/smj-research-atlas"
ALLOWED_ORIGINS={BASE.split("/smj-research-atlas")[0],
                 "http://localhost:4321","http://127.0.0.1:4321"}
DOI_PATTERN=re.compile(r"10\.1002/smj\.[0-9]+[a-z0-9-]*",re.I)
MAX_ATTEMPTS=8
MAX_CANDIDATES=14
MAX_HTTP_REQUESTS=24
MAX_OUTPUT_ROWS=12
TTL_SECONDS=1200

app=FastAPI(title="SMJ Atlas OA Analysis",version="1.0.0",docs_url=None,redoc_url=None,openapi_url=None)
app.add_middleware(CORSMiddleware,allow_origins=sorted(ALLOWED_ORIGINS),allow_credentials=False,
                   allow_methods=["GET","POST","OPTIONS"],allow_headers=["content-type"])

_lock=threading.Lock()
_semaphore=threading.BoundedSemaphore(value=1)
_cache={}
_access=defaultdict(deque)
_daily=deque()


class PaperRequest(BaseModel):
    doi: str=Field(min_length=12,max_length=90)


def valid_doi(raw):
    raw=str(raw or "").strip().lower()
    if not DOI_PATTERN.fullmatch(raw):
        raise HTTPException(status_code=422,detail="invalid_or_non_smj_doi")
    return raw


def _fixed_json(url):
    # URL must be generated by this module from a verified DOI; this helper
    # is never exposed to caller-supplied URLs.
    with httpx.Client(timeout=12,follow_redirects=False,trust_env=False,
                      headers={"User-Agent":"SMJResearchAtlas/5.0 (source analysis)"}) as client:
        with client.stream("GET",url) as response:
            if response.status_code!=200:
                raise ValueError("upstream_http_"+str(response.status_code))
            if int(response.headers.get("content-length","0"))>3_000_000:
                raise ValueError("metadata_too_large")
            content=b""
            for part in response.iter_bytes():
                content+=part
                if len(content)>3_000_000:raise ValueError("metadata_too_large")
    return json.loads(content)


def _paper_for_doi(doi):
    pid="doi:"+doi
    h=hashlib.sha256(pid.encode()).hexdigest()[:16]
    url=BASE+"/data/papers/"+h+".json"
    data=_fixed_json(url)
    if data.get("paper_id")!=pid or str(data.get("doi","")).lower()!=doi:
        raise ValueError("atlas_article_identity_mismatch")
    if not data.get("title") or not data.get("metadata_provenance"):
        raise ValueError("atlas_article_metadata_incomplete")
    return data


def _live_openalex(doi):
    # Public metadata only; always verify DOI. No abstract text is retained.
    url="https://api.openalex.org/works/https://doi.org/"+quote(doi,safe="/") + \
        "?select=doi,open_access,best_oa_location,primary_location,locations"
    try:
        raw=_fixed_json(url)
        if str(raw.get("doi","")).lower().removeprefix("https://doi.org/")!=doi:
            return {}, "openalex_doi_mismatch"
        return raw,None
    except (httpx.HTTPError,ValueError,KeyError,TypeError,RuntimeError) as exc:
        return {},type(exc).__name__


def _candidate_locations(paper,openalex):
    # Existing Atlas evidence + live OpenAlex locations are both provider-
    # asserted OA. A successful DOI alone never grants publisher PDF rights.
    locations=list((paper.get("enrichment") or {}).get("oa_locations") or [])
    for key in ("locations","best_oa_location","primary_location"):
        raw=openalex.get(key)
        if not raw:continue
        items=raw if isinstance(raw,list) else [raw]
        locations.extend(item for item in items if isinstance(item,dict)
                         and item.get("is_oa") and
                         (item.get("is_accepted") or item.get("is_published") or
                          item.get("version") in ("acceptedVersion","publishedVersion")))
    locations=merge_wiley_candidate(paper["doi"],openalex,locations)
    return source_candidates(locations,MAX_CANDIDATES)


def _evidence_summary(record,review):
    fields=record.get("fields",{}) if record else {}
    return dict(
        fields={k:field_status(fields.get(k),review,k) for k in
               ("sample_period","data_source","empirical_method")},
        hypotheses=concise_rows(record,"hypotheses")[:MAX_OUTPUT_ROWS] if record else [],
        findings=concise_rows(record,"findings")[:MAX_OUTPUT_ROWS] if record else [],
        robustness=[x for x in concise_rows(record,"checks") if
                    x["kind"] in ("robustness","sensitivity")][:MAX_OUTPUT_ROWS] if record else [],
        theory_evidence=[dict(term_id=x["term_id"],status=x["status"],
                             section=x.get("section"),page=x.get("page"),
                             source_url=x.get("source_url"),
                             evidence_ids=x.get("evidence_ids",[])[:3])
                         for x in (record or {}).get("theory_evidence",[])][:15],
    )


def analyze_oa(doi,paper_loader=_paper_for_doi,openalex_loader=_live_openalex,
               fetcher_factory=OAFetcher):
    """Run bounded full-text retrieval on ONE existing Atlas DOI."""
    paper=paper_loader(doi)
    meta=article_type(paper)
    record=paper.get("research_v4")
    # Reuse source-aligned full-text records without unnecessary re-fetch,
    # but attempt legal OA even when the original Atlas record has no text.
    raw,openalex_error=openalex_loader(doi)
    candidates=_candidate_locations(paper,raw)
    attempts=[]
    if not record and candidates:
        fetcher=fetcher_factory(interval=0.75)
        fetcher.max_requests=MAX_HTTP_REQUESTS
        try:
            for c in candidates[:MAX_ATTEMPTS]:
                url=c["url"]
                try:
                    response,redirects=fetcher.fetch(url)
                    if response.status_code!=200:
                        attempts.append(dict(source_url=url,status="http_"+str(response.status_code)))
                        if response.status_code==429:break
                        continue
                    ct=response.headers.get("content-type","")
                    if not (response.content.startswith(b"%PDF") or "html" in ct.lower()):
                        attempts.append(dict(source_url=url,status="not_pdf_or_article_html"))
                        continue
                    receipt=dict(source_url=str(response.url),source_hash=digest(response.content))
                    doc=parse_article(paper,response.content,ct,receipt)
                    parsed=extraction(doc, _ontology())
                    validate_record(parsed)
                    record=parsed
                    attempts.append(dict(source_url=url,status="parsed",
                                         resolved_url=str(response.url),pages=len(doc.blocks),
                                         redirects=max(0,len(redirects)-1)))
                    break
                except PolicyError as exc:
                    attempts.append(dict(source_url=url,status=str(exc)))
                    if str(exc) in {"global_request_budget","host_retry_after"}:break
                except (ValueError,KeyError,RuntimeError) as exc:
                    attempts.append(dict(source_url=url,status=type(exc).__name__,
                                         diagnostic=str(exc)[:110]))
                except Exception as exc:
                    attempts.append(dict(source_url=url,status="network_or_parser_failure",
                                         diagnostic=type(exc).__name__))
        finally:
            fetcher.close()
    details=_evidence_summary(record,meta["type"]=="review_or_synthesis")
    # No raw PDF bytes, complete HTML text, or unrestricted body excerpts.
    return dict(schema_version="live-oa-v1",doi=doi,title=paper["title"],
                generated_at=datetime.now(timezone.utc).isoformat(),
                article_type=meta,oa_openalex_is_oa=bool((raw.get("open_access") or {}).get("is_oa")),
                acquisition_status=("source_extracted" if record and attempts and
                                    attempts[-1]["status"]=="parsed" else
                                    "existing_validated_fulltext" if record else
                                    "no_provider_oa_source" if not candidates else
                                    "fulltext_not_acquired"),
                sources_considered=len(candidates),attempts=attempts,
                openalex_metadata_error=openalex_error,
                source_url=record.get("source_url") if record else None,
                source_hash=record.get("source_hash") if record else None,
                evidence_state="source_located_not_semantically_certified" if record
                               else "insufficient_fulltext",
                limitations=["OA indication does not guarantee HTTP access",
                             "No data does not mean no hypotheses, estimates or robustness",
                             "Automatically aligned text is not expert semantic validation"],
                **details)


# Lazy, per-instance ontology. The bundle contains no copyrighted content.
_ontology_cache=None
def _ontology():
    global _ontology_cache
    if _ontology_cache is None:
        from pathlib import Path
        _ontology_cache=json.loads((Path(__file__).resolve().parents[1]/
                                     "data/ontology.yaml").read_text(encoding="utf-8"))
    return _ontology_cache


def _allow_ip(ip):
    t=time.monotonic()
    with _lock:
        while _daily and t-_daily[0]>86400:_daily.popleft()
        q=_access[ip]
        while q and t-q[0]>3600:q.popleft()
        if len(_daily)>=60 or len(q)>=4:return False
        _daily.append(t);q.append(t)
        return True


@app.get("/api/health")
def health():
    return {"status":"ok","service":"smj-oa-on-demand"}


@app.post("/api/analyze")
def analyze(payload:PaperRequest,request:Request):
    # CORS controls browsers. Explicit Origin validation plus bounded quotas
    # also rejects accidental cross-site usage. This is not authenticated API.
    origin=request.headers.get("origin")
    if origin not in ALLOWED_ORIGINS:
        raise HTTPException(403,detail="site_origin_required")
    doi=valid_doi(payload.doi)
    t=time.monotonic()
    with _lock:
        cached=_cache.get(doi)
        if cached and t-cached[0]<TTL_SECONDS:
            return dict(cached[1],cached=True)
    ip=(request.client.host if request.client else "unknown")
    if not _allow_ip(ip):
        raise HTTPException(429,detail="limited_oa_requests; retry_later")
    if not _semaphore.acquire(blocking=False):
        raise HTTPException(429,detail="another_oa_analysis_in_progress")
    try:
        result=analyze_oa(doi)
        with _lock:_cache[doi]=(time.monotonic(),result)
        return result
    except (ValueError,httpx.HTTPError,KeyError) as exc:
        raise HTTPException(502,detail="trusted_metadata_unavailable:"+type(exc).__name__) from exc
    finally:
        _semaphore.release()
